  /// 등록되지 않은 캐릭터/상황이면 null을 반환해 호출부가 기본 멘트로 대체한다.
  static String? pick(String tutorId, CoachSituation s) {
    final bank = banks[tutorId];
    final list = bank?[s];
    if (list == null || list.isEmpty) return null;
    return list[_rand.nextInt(list.length)];
  }

  /// 캐릭터의 전체 행동패턴 수
  static int countOf(String tutorId) {
    final bank = banks[tutorId];
    if (bank == null) return 0;
    return bank.values.fold(0, (a, b) => a + b.length);
  }

