# 과목 무관 공용: 이미지 문항은 난이도 상향
def classify_topic(track_id, subject, text):
    """문항 텍스트로 토픽 결정."""
    rules = TOPIC_RULES.get(track_id, {}).get(subject)
    if not rules:
        return subject  # 규칙 없으면 과목명 그대로
    best, best_score = rules[0][0], 0
    for topic, keywords in rules:
        score = sum(1 for kw in keywords if kw in text)
        if score > best_score:
            best, best_score = topic, score
    return best


def estimate_difficulty(question, options, has_image):
    """난이도 휴리스틱: 계산형·긴 지문·그림 → 상, 단답 암기형 → 하."""
    text = question + ' '.join(options)
    calc = sum(text.count(c) for c in ['=', '√', '×', '²', '³', 'log', 'sin', 'cos'])
    digits = sum(ch.isdigit() for ch in text)
    score = 0
    if has_image:
        score += 1
    if calc >= 2 or digits >= 20:
        score += 1
    if len(question) > 120:
        score += 1
    if len(question) < 45 and digits < 6 and not has_image:
        score -= 1
    if score <= -1:
        return 1
    if score >= 2:
        return 3
    return 2 if score == 1 else (1 if len(question) < 60 and digits < 8 else 2)


def difficulty_raw(question, options, has_image):
    """연속형 난이도 원점수 (분위수 배정용, 전기기사 분포 매칭)."""
    text = question + ' '.join(options)
    calc = sum(text.count(c) for c in
               ['=', '√', '×', '²', '³', 'log', 'sin', 'cos', 'Ω', 'π'])
    digits = sum(ch.isdigit() for ch in text)
    return (calc * 3.0 + digits * 0.5 + len(question) * 0.06
            + (8.0 if has_image else 0.0))
